def pick(n: int, seed: str | None = None, offset: int = 0) -> list[dict[str, str]]:
    """`n` quotes in a rotation that changes every day (seed = today's date) and shifts on each refresh (offset)."""
    rng = random.Random(seed or date.today().isoformat())
    order = list(QUOTES)
    rng.shuffle(order)
    out = []
    for i in range(max(0, n)):
        text, author = order[(offset + i) % len(order)]
        out.append({"text": text, "author": author})
    return out
